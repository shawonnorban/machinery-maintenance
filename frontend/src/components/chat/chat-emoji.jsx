const RECENT = "annotech.chat.emoji.recent";

function readRecent() {
  try {
    return JSON.parse(localStorage.getItem(RECENT) ?? "[]").slice(0, 32);
  } catch {
    return [];
  }
}

/** Remembers a pick for the Recent row (this browser only). */
export function rememberEmoji(e) {
  try {
    localStorage.setItem(RECENT, JSON.stringify([e, ...readRecent().filter((x) => x !== e)].slice(0, 32)));
  } catch {
    /* recent only where storage works */
  }
}

/** The picker: category icons on top (the open one underlined in green), the grid of that category below. */
export function EmojiPicker({ onPick, t, className, height = "h-64" }) {
  const [recent] = useState(readRecent);
  const groups = recent.length ? [{ key: "recent", icon: "🕘", list: recent }, ...EMOJI_GROUPS] : EMOJI_GROUPS;
  const [open, setOpen] = useState(groups[0].key);
  const group = groups.find((g) => g.key === open) ?? groups[0];
  const pick = (e) => {
    rememberEmoji(e);
    onPick(e);
  };

  return (
    <div className={cn("chat-emoji flex flex-col bg-[#f0f2f5]", className)} onMouseDown={(e) => e.preventDefault()}>
      <div className="flex shrink-0 items-center gap-0.5 border-b border-[#e9edef] px-2">
        {groups.map((g) => (
          <button
            key={g.key}
            type="button"
            title={t ? t(`emoji_groups.${g.key}`) : g.key}
            aria-label={t ? t(`emoji_groups.${g.key}`) : g.key}
            onClick={() => setOpen(g.key)}
            className={cn("flex-1 border-b-[3px] py-2 text-[20px] leading-none transition-[filter,opacity]", open === g.key ? "border-[#00a884]" : "border-transparent opacity-60 grayscale hover:opacity-100 hover:grayscale-0")}
          >
            {g.icon}
          </button>
        ))}
      </div>
      <p className="shrink-0 px-3 pt-2 pb-1 text-[12.5px] text-[#667781]">{t ? t(`emoji_groups.${group.key}`) : group.key}</p>
      <div className={cn("grid grid-cols-[repeat(auto-fill,minmax(40px,1fr))] content-start overflow-y-auto px-2 pb-2", height)}>
        {group.list.map((e, i) => (
          <button key={`${e}-${i}`} type="button" onClick={() => pick(e)} className="flex aspect-square items-center justify-center rounded-md text-[26px] leading-none transition-transform hover:scale-110 hover:bg-black/5">
            {e}
          </button>
        ))}
      </div>
    </div>
  );
}
